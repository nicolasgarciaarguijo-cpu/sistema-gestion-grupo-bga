// no se pudo reconstruir que habia pasado: solo quedaba que modulo se habia guardado.
const pago = (extra: any = {}) => ({ id: 1, company: "De Raiz", supplier: "Dac", date: "2026-11-10", amount: 1500000, cuentaId: "banco|x", ...extra });

describe("diferencias de una coleccion", () => {
  it("un campo cambiado: que tenia y que tiene", () => {
    const r = diferencias("costEntries", [pago()], [pago({ amount: 1800000 })]);
    expect(r).toHaveLength(1);
    expect(r[0]).toMatchObject({ coleccion: "costEntries", refId: "1", company: "De Raiz", accion: "cambio" });
    expect(r[0].cambios).toEqual([{ campo: "amount", antes: "1500000", despues: "1800000" }]);
    expect(r[0].resumen).toContain("Dac");
  });

  it("alta y baja", () => {
    expect(diferencias("costEntries", [], [pago()])[0]).toMatchObject({ accion: "alta", cambios: [] });
    expect(diferencias("costEntries", [pago()], [])[0]).toMatchObject({ accion: "baja" });
  });

  it("no anota lo que no cambio, ni la firma automatica, ni vacio contra vacio", () => {
    const a = pago();
    expect(diferencias("costEntries", [a], [a])).toEqual([]);
    expect(diferencias("costEntries", [pago()], [pago({ firmadoEn: "2026-11-21T10:00:00Z" })])).toEqual([]);
    expect(diferencias("costEntries", [pago({ notes: undefined })], [pago({ notes: "" })])).toEqual([]);
  });

  it("lo que el sistema arma solo no es una carga de nadie", () => {
    expect(diferencias("financialItems", [], [{ id: 9, autoGenerated: true }])).toEqual([]);
    expect(diferencias("financialItems", [{ id: 9, autoGenerated: true }], [])).toEqual([]);
    // Ni cuando se recalcula: en la copia de prueba aparecia "el usuario cambio la fecha" de un reflejo automatico.
    expect(diferencias("financialItems", [{ id: 9, autoGenerated: true, date: "2026-11-21" }], [{ id: 9, autoGenerated: true, date: "2026-11-22" }])).toEqual([]);
  });

  it("un objeto adentro se compara por contenido", () => {
    expect(diferencias("purchaseInvoices", [{ id: 1, saldo: { fecha: "a" } }], [{ id: 1, saldo: { fecha: "a" } }])).toEqual([]);
    expect(diferencias("purchaseInvoices", [{ id: 1, saldo: { fecha: "a" } }], [{ id: 1, saldo: { fecha: "b" } }])[0].cambios[0].campo).toBe("saldo");
  });
});

describe("los cobros de un trabajo se siguen de a uno", () => {
  const hijos = ["payments", "cobrosPrevistos"];
  const trabajo = (extra: any) => ({ id: 7, company: "BGA", client: "Contract Rent", budgetNumber: "3395", payments: [], cobrosPrevistos: [], ...extra });
  const cobro = { id: 12, amount: 2974474, paymentDate: "2026-11-06", estado: "estimado" };

  it("cambiar la fecha de un cobro anota el cobro, no el trabajo entero", () => {
    const r = diferencias("approvedJobs", [trabajo({ payments: [cobro] })], [trabajo({ payments: [{ ...cobro, paymentDate: "2026-11-20" }] })], hijos);
    expect(r).toHaveLength(1);
    expect(r[0]).toMatchObject({ refId: "12", padreId: "7", hijo: "payments", accion: "cambio", company: "BGA" });
    expect(r[0].cambios).toEqual([{ campo: "paymentDate", antes: "2026-11-06", despues: "2026-11-20" }]);
    expect(r[0].resumen).toContain("Contract Rent");
  });

  it("borrar un cobro queda anotado como baja, con el trabajo y el monto", () => {
    const r = diferencias("approvedJobs", [trabajo({ payments: [cobro] })], [trabajo({ payments: [] })], hijos);
    expect(r).toHaveLength(1);
    expect(r[0]).toMatchObject({ accion: "baja", refId: "12", hijo: "payments" });
    expect(r[0].resumen).toContain("2.974.474");
  });

  it("confirmar un cobro programado es UN cambio (de lista y de estado), no una baja y un alta", () => {
    const antes = [trabajo({ cobrosPrevistos: [cobro] })];
    const despues = [trabajo({ payments: [{ ...cobro, estado: undefined, paymentDate: "2026-11-20", cuentaId: "banco|BGA|santander|ARS" }], cobrosPrevistos: [] })];
    const r = diferencias("approvedJobs", antes, despues, hijos);
    expect(r).toHaveLength(1);
    expect(r[0].accion).toBe("cambio");
    expect(r[0].cambios[0]).toEqual({ campo: "lista", antes: "cobrosPrevistos", despues: "payments" });
    expect(r[0].cambios.map((c) => c.campo)).toEqual(expect.arrayContaining(["estado", "paymentDate", "cuentaId"]));
  });

  it("un cambio en el trabajo mismo se anota aparte de sus cobros", () => {
    const r = diferencias("approvedJobs", [trabajo({ payments: [cobro], status: "en curso" })], [trabajo({ payments: [cobro], status: "finalizado" })], hijos);
    expect(r).toHaveLength(1);
    expect(r[0]).toMatchObject({ refId: "7", accion: "cambio" });
    expect(r[0].padreId).toBeUndefined();
  });
});

describe("juntar los cambios seguidos", () => {
  const cambio = (antes: string, despues: string, campo = "amount") => ({ coleccion: "costEntries", refId: "1", company: "De Raiz", accion: "cambio" as const, resumen: "Dac", cambios: [{ campo, antes, despues }] });

  it("tipear un monto tecla por tecla queda como un solo cambio", () => {
    const r = juntarCambios([cambio("", "1"), cambio("1", "15"), cambio("15", "150"), cambio("150", "1500")]);
    expect(r).toHaveLength(1);
    expect(r[0].cambios).toEqual([{ campo: "amount", antes: "", despues: "1500" }]);
  });

  it("si el campo vuelve a su valor, no se anota nada", () => {
    expect(juntarCambios([cambio("100", "200"), cambio("200", "100")])).toEqual([]);
  });

  it("campos distintos del mismo registro van juntos", () => {
    const r = juntarCambios([cambio("100", "200"), cambio("a", "b", "supplier")]);
    expect(r).toHaveLength(1);
    expect(r[0].cambios.map((c) => c.campo)).toEqual(["amount", "supplier"]);
  });

  it("cargar algo y completarlo es un alta; cargarlo y borrarlo enseguida no deja nada", () => {
    const alta = { coleccion: "costEntries", refId: "1", company: "", accion: "alta" as const, resumen: "#1", cambios: [] };
    const baja = { ...alta, accion: "baja" as const };
    const conDatos = juntarCambios([alta, { ...cambio("", "1500"), resumen: "Dac · $ 1.500" }]);
    expect(conDatos).toHaveLength(1);
    expect(conDatos[0]).toMatchObject({ accion: "alta", resumen: "Dac · $ 1.500" });
    expect(juntarCambios([alta, baja])).toEqual([]);
  });

  it("registros distintos no se mezclan", () => {
    expect(juntarCambios([cambio("1", "2"), { ...cambio("1", "2"), refId: "2" }])).toHaveLength(2);
  });
});

describe("para mostrar", () => {
  it("valores como texto corto", () => {
    expect(comoTexto(true)).toBe("sí");
    expect(comoTexto(null)).toBe("");
    expect(comoTexto([1, 2])).toBe("(2 ítems)");
    expect(comoTexto("x".repeat(200)).length).toBeLessThan(90);
  });
  it("nombres en criollo", () => {
    expect(queEs({ coleccion: "approvedJobs", hijo: "payments" })).toBe("Trabajo aprobado · cobro");
    expect(queEs({ coleccion: "costEntries" })).toBe("Pago");
  });
});

describe("los campos se leen en criollo", () => {
  it("traduce los campos conocidos y deja los demas como estan", () => {
    expect(cambioLegible({ campo: "paymentDate", antes: "2026-11-06", despues: "2026-12-05" })).toEqual({ campo: "fecha", antes: "2026-11-06", despues: "2026-12-05" });
    expect(cambioLegible({ campo: "lista", antes: "cobrosPrevistos", despues: "payments" })).toEqual({ campo: "pasó de", antes: "programado", despues: "cobrado" });
    expect(cambioLegible({ campo: "campoRaro", antes: "a", despues: "b" }).campo).toBe("campoRaro");
  });
});
