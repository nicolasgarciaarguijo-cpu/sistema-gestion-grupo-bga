import { aplicarBorrado, esReciente, sellarAltas, separarBorrado, sinYaPedidos, VENTANA_BORRADO_MS } from "./borradoProtegido";

const ahora = Date.parse("2026-11-12T15:00:00Z");
const hace = (min: number) => new Date(ahora - min * 60 * 1000).toISOString();

describe("borrado protegido", () => {
  it("sella creadoEn solo en lo nuevo", () => {
    const prev = [{ id: 1, amount: 10 }];
    const next = sellarAltas(prev, [...prev, { id: 2, amount: 5 }], ahora);
    expect((next[0] as any).creadoEn).toBeUndefined();
    expect((next[1] as any).creadoEn).toBe(new Date(ahora).toISOString());
  });

  it("sella los hijos nuevos (un cobro nuevo dentro del trabajo)", () => {
    const prev = [{ id: 1, payments: [{ id: 10 }] }];
    const next = sellarAltas(prev, [{ id: 1, payments: [{ id: 10 }, { id: 11 }] }], ahora, ["payments"]);
    expect((next[0] as any).payments[1].creadoEn).toBeDefined();
    expect((next[0] as any).payments[0].creadoEn).toBeUndefined();
  });

  it("dentro de la hora se borra; pasada la hora o sin sello, se repone y queda bloqueado", () => {
    const prev = [
      { id: 1, creadoEn: hace(30), amount: 1 },
      { id: 2, creadoEn: hace(90), amount: 2 },
      { id: 3, amount: 3 },
    ];
    const r = separarBorrado("costEntries", prev, [], { puedeTodo: false, ahora });
    expect(r.lista.map((x) => x.id)).toEqual([2, 3]);
    expect(r.bloqueados.map((b) => b.refId)).toEqual([2, 3]);
  });

  it("lo que el sistema arma solo (autoGenerated) no se protege", () => {
    expect(separarBorrado("financialItems", [{ id: 1, autoGenerated: true }], [], { puedeTodo: false, ahora }).lista).toEqual([]);
  });

  it("el superadmin borra todo sin pedir", () => {
    const prev = [{ id: 2, creadoEn: hace(90) }];
    expect(separarBorrado("x", prev, [], { puedeTodo: true, ahora }).lista).toEqual([]);
  });

  it("si solo se quiso borrar algo viejo, devuelve la misma lista (sin render de mas)", () => {
    const prev = [{ id: 1 }, { id: 2 }];
    const r = separarBorrado("x", prev, [prev[0]], { puedeTodo: false, ahora });
    expect(r.lista).toBe(prev);
  });

  it("los demas cambios pasan aunque el borrado quede bloqueado", () => {
    const prev = [{ id: 1, amount: 1 }, { id: 2, amount: 2 }];
    const r = separarBorrado("x", prev, [{ id: 2, amount: 20 }], { puedeTodo: false, ahora });
    expect(r.lista).toEqual([{ id: 1, amount: 1 }, { id: 2, amount: 20 }]);
  });

  it("protege los hijos: un cobro viejo de un trabajo", () => {
    const prev = [{ id: 1, company: "DR", payments: [{ id: 10, amount: 100 }, { id: 11, amount: 5, creadoEn: hace(5) }] }];
    const r = separarBorrado("approvedJobs", prev, [{ id: 1, company: "DR", payments: [] }], { puedeTodo: false, ahora, hijos: ["payments"] });
    expect((r.lista[0] as any).payments.map((p: any) => p.id)).toEqual([10]);
    expect(r.bloqueados).toEqual([expect.objectContaining({ refId: 10, padreId: 1, hijo: "payments", company: "DR" })]);
    // y autorizado, se borra
    expect((aplicarBorrado(r.lista as any, r.bloqueados)[0] as any).payments).toEqual([]);
  });

  it("no repite un pedido pendiente", () => {
    const b = [{ coleccion: "x", refId: 1, resumen: "" }];
    const pedidos = [{ id: 9, company: "DR", pedidoPor: "J", pedidoEn: "", estado: "pendiente" as const, items: b }];
    expect(sinYaPedidos(b, pedidos)).toEqual([]);
    expect(sinYaPedidos(b, [{ ...pedidos[0], estado: "rechazado" }])).toHaveLength(1);
  });

  it("la ventana es de una hora", () => {
    expect(esReciente(new Date(ahora - VENTANA_BORRADO_MS + 1000).toISOString(), ahora)).toBe(true);
    expect(esReciente(new Date(ahora - VENTANA_BORRADO_MS - 1000).toISOString(), ahora)).toBe(false);
    expect(esReciente(undefined, ahora)).toBe(false);
  });
});
