export type ItemPlanilla = {
  id: number;
  company: string;
  date: string;
  type: string; // "pago" | "cobranza" | "facturacion"
  status?: string;
  title: string;
  amount: number;
  administration?: "blanco" | "negro";
  conceptKey?: string;
  incomeCategory?: string;
  autoGenerated?: boolean;
  sourceJobId?: number;
};

export type FilaCarga = {
  id: number;
  company: string;
  date: string;
  renglon: string; // nombre del renglon (o del renglon propio)
  seccion: string;
  titulo: string;
  monto: number;
  administration: "blanco" | "negro";
  destino: DestinoCarga;
  desdeCorte: boolean;
  futura: boolean;
  posibleDoble: string; // "" o que se encontro en la solapa
};

// Pagos ya cargados en su solapa, para avisar el posible doble.
export type YaCargado = { company: string; date: string; amount: number; nombre: string };

const norm = (s: string) =>
  (s || "")
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9 ]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

const dias = (a: string, b: string) => Math.abs(Date.parse(`${a.slice(0, 10)}T00:00:00Z`) - Date.parse(`${b.slice(0, 10)}T00:00:00Z`)) / 86400000;

// "custom:haberes:LUCAS RUIZ" -> { seccion: "haberes", renglon: "LUCAS RUIZ" }
export function partirClave(conceptKey: string, seccionDe: (ck: string) => { seccion: string; label: string } | undefined) {
  const ck = conceptKey || "";
  if (ck.startsWith("custom:")) {
    const [, seccion, ...resto] = ck.split(":");
    return { seccion: seccion || "", renglon: resto.join(":") };
  }
  const s = seccionDe(ck);
  return { seccion: s?.seccion || "", renglon: s?.label || ck };
}

export function destinoDe(seccion: string, texto: string, item: Pick<ItemPlanilla, "type" | "incomeCategory">): DestinoCarga {
  const t = norm(texto);
  if (item.type === "cobranza" && (!item.incomeCategory || item.incomeCategory === "trabajo") && seccion === "cobranzas") return "trabajos";
  if (seccion === "haberes" || seccion === "cargas_sociales") return /sindicato|ccss|art |obra soc|seg soc|931/.test(` ${t} `) ? "costos" : "personal";
  if (seccion === "impuestos") return /cuota|plan /.test(`${t} `) ? "deudas" : "costos";
  if (seccion === "prestamos" || /aporte|prestamo|pretamo/.test(t)) return "movimientosInternos";
  if (seccion === "inversiones" || /fondo|fci|plazo fijo|caucion/.test(t)) return "inversiones";
  if (seccion === "bancos") return /cuota|plan /.test(`${t} `) ? "deudas" : "bancos";
  if (seccion === "ingresos_varios" || seccion === "cobranzas") return "otros";
  if (item.type === "pago") return "costos";
  return "otros";
}

export function cargasDePlanilla(input: {
  items: ItemPlanilla[];
  seccionDe: (ck: string) => { seccion: string; label: string } | undefined;
  hoy: string;
  corte: string; // desde cuando la carga mueve los saldos reales (29/08/2026)
  desde: string; // inicio del ejercicio abierto
  haberesPagados?: YaCargado[]; // pagos de la ficha de haberes (nombre = persona)
  pagosProveedores?: YaCargado[]; // pagos de Pago a proveedores (nombre = proveedor)
}): FilaCarga[] {
  const { items, seccionDe, hoy, corte, desde } = input;
  const mes = (iso: string) => iso.slice(0, 7);
  return items
    // Solo lo cargado a mano: lo autogenerado (reflejo de facturas y pagos de trabajos) ya vive en su lugar.
    .filter((i) => !i.autoGenerated && i.sourceJobId == null && (i.date || "") >= desde)
    .map((i) => {
      const { seccion, renglon } = partirClave(i.conceptKey || "", seccionDe);
      const destino = destinoDe(seccion, `${renglon} ${i.title}`, i);
      const monto = Math.abs(Number(i.amount) || 0);
      let posibleDoble = "";
      if (destino === "personal") {
        const quien = norm(renglon || i.title);
        const hit = (input.haberesPagados || []).find(
          (p) => p.company === i.company && mes(p.date) === mes(i.date) && quien && (norm(p.nombre).includes(quien) || quien.includes(norm(p.nombre)))
        );
        if (hit) posibleDoble = `también hay un pago de haberes a ${hit.nombre} ese mes`;
      } else if (destino === "costos") {
        const hit = (input.pagosProveedores || []).find(
          (p) => p.company === i.company && Math.abs(p.amount - monto) <= 1 && dias(p.date, i.date) <= 5
        );
        if (hit) posibleDoble = `en Pago a proveedores hay uno igual (${hit.nombre || "sin proveedor"})`;
      }
      return {
        id: i.id,
        company: i.company,
        date: i.date,
        renglon,
        seccion,
        titulo: i.title || renglon,
        monto,
        administration: i.administration === "negro" ? "negro" : "blanco",
        destino,
        desdeCorte: i.date >= corte,
        futura: i.date > hoy,
        posibleDoble,
      } as FilaCarga;
    })
    .sort((a, b) => b.date.localeCompare(a.date));
}
