import { cargasDePlanilla, destinoDe } from "./cargasPlanilla";

const seccionDe = (ck: string) => (ck === "b_imp_debito" ? { seccion: "bancos", label: "Impuesto al débito" } : undefined);

describe("cargas viejas de la planilla", () => {
  it("cada renglon va a su solapa", () => {
    expect(destinoDe("haberes", "LUCAS RUIZ", { type: "pago" })).toBe("personal");
    expect(destinoDe("cargas_sociales", "SINDICATO CABA USIMRA", { type: "pago" })).toBe("costos");
    expect(destinoDe("impuestos", "IVA PLAN 12 CUOTAS", { type: "pago" })).toBe("deudas");
    expect(destinoDe("compras_insumos", "DAC", { type: "pago" })).toBe("costos");
    expect(destinoDe("ingresos_varios", "APORTE DE CAPITAL NICOLAS", { type: "cobranza" })).toBe("movimientosInternos");
    expect(destinoDe("inversiones", "Retiro de Fondo Lombard", { type: "cobranza" })).toBe("inversiones");
    expect(destinoDe("bancos", "Impuesto al débito", { type: "pago" })).toBe("bancos");
    expect(destinoDe("ingresos_varios", "VENTA DE HIERRO", { type: "cobranza" })).toBe("otros");
  });

  it("deja afuera lo autogenerado y lo de ejercicios cerrados; marca corte, futuras y posibles dobles", () => {
    const filas = cargasDePlanilla({
      items: [
        { id: 1, company: "DR", date: "2026-09-05", type: "pago", title: "LUCAS RUIZ MANSILLA", amount: 1000, conceptKey: "custom:haberes:LUCAS RUIZ MANSILLA" },
        { id: 2, company: "DR", date: "2026-09-28", type: "pago", title: "Grupo Remac", amount: 500, conceptKey: "custom:compra_materiales:Grupo Remac" },
        { id: 3, company: "DR", date: "2026-11-02", type: "pago", title: "DAC", amount: 70, conceptKey: "custom:compra_materiales:DAC" },
        { id: 4, company: "DR", date: "2026-03-01", type: "pago", title: "debito", amount: 9, conceptKey: "b_imp_debito" },
        { id: 5, company: "DR", date: "2026-09-01", type: "cobranza", title: "auto", amount: 9, autoGenerated: true },
        { id: 6, company: "DR", date: "2025-10-01", type: "pago", title: "viejo", amount: 9 },
      ],
      seccionDe,
      hoy: "2026-10-17",
      corte: "2026-08-29",
      desde: "2025-11-01",
      haberesPagados: [{ company: "DR", date: "2026-09-04", amount: 1000, nombre: "Lucas Ruiz Mansilla" }],
      pagosProveedores: [{ company: "DR", date: "2026-09-30", amount: 500, nombre: "GRUPO REMAC SRL" }],
    });
    expect(filas.map((f) => f.id)).toEqual([3, 2, 1, 4]);
    const por = (id: number) => filas.find((f) => f.id === id)!;
    expect(por(1).posibleDoble).toContain("haberes");
    expect(por(2).posibleDoble).toContain("Pago a proveedores");
    expect(por(3).futura).toBe(true);
    expect(por(4)).toMatchObject({ desdeCorte: false, destino: "bancos", renglon: "Impuesto al débito" });
  });
});
