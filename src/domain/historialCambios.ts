import { resumenDe } from "./borradoProtegido";

export type CambioDeCampo = { campo: string; antes: string; despues: string };
export type CambioDeRegistro = {
  coleccion: string;
  refId: string;
  padreId?: string;
  hijo?: string;
  company: string;
  accion: "alta" | "cambio" | "baja";
  resumen: string;
  cambios: CambioDeCampo[];
};

type ConId = { id: number | string; [k: string]: any };

// Campos que cambian solos en cada edicion: no dicen nada y llenarian el historial.
const SIN_INTERES = new Set(["firmadoEn", "creadoEn", "updatedAt", "savedAt"]);
const MAX_TEXTO = 80;

/** Un valor como texto corto para mostrar. */
export function comoTexto(v: any): string {
  if (v === undefined || v === null || v === "") return "";
  if (typeof v === "boolean") return v ? "sí" : "no";
  if (typeof v === "number") return String(v);
  if (typeof v === "string") return v.length > MAX_TEXTO ? `${v.slice(0, MAX_TEXTO)}…` : v;
  if (Array.isArray(v)) return `(${v.length} ${v.length === 1 ? "ítem" : "ítems"})`;
  return "(datos)";
}

const igual = (a: any, b: any): boolean => {
  if (a === b) return true;
  const vacio = (x: any) => x === undefined || x === null || x === "";
  if (vacio(a) && vacio(b)) return true;
  if (typeof a === "object" || typeof b === "object") return JSON.stringify(a ?? null) === JSON.stringify(b ?? null);
  return false;
};

function camposCambiados(antes: ConId, despues: ConId, omitir: Set<string>): CambioDeCampo[] {
  const out: CambioDeCampo[] = [];
  const claves = new Set([...Object.keys(antes || {}), ...Object.keys(despues || {})]);
  claves.forEach((k) => {
    if (k === "id" || SIN_INTERES.has(k) || omitir.has(k)) return;
    if (igual(antes[k], despues[k])) return;
    out.push({ campo: k, antes: comoTexto(antes[k]), despues: comoTexto(despues[k]) });
  });
  return out;
}

function compararListas(
  coleccion: string,
  prev: ConId[],
  next: ConId[],
  extra: { padreId?: string; hijo?: string; company?: string; padreResumen?: string },
  omitir: Set<string>,
  out: CambioDeRegistro[]
) {
  const antes = new Map((prev || []).filter((x) => x && x.id != null).map((x) => [x.id, x]));
  const ahora = new Map((next || []).filter((x) => x && x.id != null).map((x) => [x.id, x]));
  const base = (x: ConId) => ({
    coleccion,
    refId: String(x.id),
    ...(extra.padreId != null ? { padreId: extra.padreId, hijo: extra.hijo } : {}),
    company: String(x.company || extra.company || ""),
    resumen: extra.padreResumen ? `${extra.padreResumen} → ${resumenDe(x)}` : resumenDe(x),
  });
  ahora.forEach((x, id) => {
    const a = antes.get(id);
    if (!a) {
      // Lo que el sistema arma solo (los reflejos de los trabajos en el calendario) no es una carga de nadie.
      if (!x.autoGenerated) out.push({ ...base(x), accion: "alta", cambios: [] });
      return;
    }
    // Lo que el sistema recalcula solo (el reflejo de un trabajo en la planilla) no es un cambio de nadie.
    if (a === x || x.autoGenerated) return;
    const cambios = camposCambiados(a, x, omitir);
    if (cambios.length) out.push({ ...base(x), accion: "cambio", cambios });
  });
  antes.forEach((a, id) => {
    if (!ahora.has(id) && !a.autoGenerated) out.push({ ...base(a), accion: "baja", cambios: [] });
  });
}

/**
 * Lo que cambio entre el antes y el despues de una coleccion. `hijos` son las listas de adentro de cada registro
 * que tambien se siguen de a uno (los cobros, las facturas y las comisiones de un trabajo).
 */
export function diferencias(coleccion: string, prev: ConId[], next: ConId[], hijos: string[] = []): CambioDeRegistro[] {
  const out: CambioDeRegistro[] = [];
  if (!Array.isArray(prev) || !Array.isArray(next) || prev === next) return out;
  const omitir = new Set(hijos);
  compararListas(coleccion, prev, next, {}, omitir, out);
  if (hijos.length) {
    const antes = new Map(prev.filter((x) => x && x.id != null).map((x) => [x.id, x]));
    next.forEach((padre) => {
      const a = padre && antes.get(padre.id);
      if (!a || a === padre) return;
      // MOVER NO ES BORRAR NI CARGAR: un cobro que pasa de previsto a realizado cambia de lista dentro del mismo
      // trabajo. Se anota como un cambio de estado, no como una baja y un alta.
      const dondeEstaba = new Map<number | string, string>();
      hijos.forEach((h) => (Array.isArray(a[h]) ? a[h] : []).forEach((x: ConId) => x && x.id != null && dondeEstaba.set(x.id, h)));
      const movidos = new Set<number | string>();
      hijos.forEach((h) =>
        (Array.isArray(padre[h]) ? padre[h] : []).forEach((x: ConId) => {
          const de = x && x.id != null ? dondeEstaba.get(x.id) : undefined;
          if (!de || de === h) return;
          movidos.add(x.id);
          const viejo = (a[de] as ConId[]).find((y) => y.id === x.id)!;
          out.push({
            coleccion,
            refId: String(x.id),
            padreId: String(padre.id),
            hijo: h,
            company: String(padre.company || ""),
            accion: "cambio",
            resumen: `${resumenDe(padre)} → ${resumenDe(x)}`,
            cambios: [{ campo: "lista", antes: de, despues: h }, ...camposCambiados(viejo, x, new Set())],
          });
        })
      );
      hijos.forEach((h) => {
        const sin = (l: any) => (Array.isArray(l) ? l : []).filter((x: ConId) => !x || !movidos.has(x.id));
        if (a[h] === padre[h]) return;
        compararListas(coleccion, sin(a[h]), sin(padre[h]), { padreId: String(padre.id), hijo: h, company: String(padre.company || ""), padreResumen: resumenDe(padre) }, new Set(), out);
      });
    });
  }
  return out;
}

const clave = (c: CambioDeRegistro) => `${c.coleccion}|${c.padreId ?? ""}|${c.hijo ?? ""}|${c.refId}`;

/**
 * Junta varios cambios seguidos del mismo registro en uno solo (escribir un monto es un cambio por tecla): de
 * cada campo queda el primer "antes" y el ultimo "despues". Un alta seguida de cambios sigue siendo un alta; un
 * alta y una baja en el mismo lote se anulan; un campo que volvio a su valor no se anota.
 */
export function juntarCambios(lote: CambioDeRegistro[]): CambioDeRegistro[] {
  const porRegistro = new Map<string, CambioDeRegistro>();
  lote.forEach((c) => {
    const k = clave(c);
    const previo = porRegistro.get(k);
    if (!previo) {
      porRegistro.set(k, { ...c, cambios: c.cambios.map((x) => ({ ...x })) });
      return;
    }
    if (previo.accion === "alta" && c.accion === "baja") {
      porRegistro.delete(k);
      return;
    }
    if (c.accion === "baja") {
      porRegistro.set(k, { ...c, cambios: [] });
      return;
    }
    if (previo.accion === "alta") {
      previo.resumen = c.resumen;
      return;
    }
    previo.resumen = c.resumen;
    c.cambios.forEach((x) => {
      const ya = previo.cambios.find((y) => y.campo === x.campo);
      if (ya) ya.despues = x.despues;
      else previo.cambios.push({ ...x });
    });
    previo.cambios = previo.cambios.filter((x) => x.antes !== x.despues);
    if (previo.accion === "cambio" && previo.cambios.length === 0) porRegistro.delete(k);
  });
  return Array.from(porRegistro.values());
}

