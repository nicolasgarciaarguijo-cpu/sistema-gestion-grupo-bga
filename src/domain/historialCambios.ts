// Como funciona: todas las colecciones de registros ya pasan por `vigilar` (App.tsx, el del borrado protegido),
// que ve el antes y el despues de cada cambio hecho por un usuario. Aca se compara uno contra otro. Lo que sale se
// junta unos segundos (tipear "1500" son cuatro cambios: queda uno solo, de vacio a 1500) y se agrega a la tabla
// `registro_cambios`, que solo crece: nadie edita ni borra una fila, y dos sesiones a la vez no se pisan.
